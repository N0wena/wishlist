/**
 * Тип лота из дизайн-хендоффа. `image` обязателен: лот без фото — дырка в кольце.
 * Полей `status` / бронирования в данных нет намеренно — не возвращать.
 */
export type Lot = {
  id: string
  /** Название вещи. */
  title: string
  /** «Категория · ориентир 42 000 ₽» — часть до « · » берётся как тег в деталке. */
  subtitle: string
  /** Зачем мне это, моими словами. */
  note?: string
  /** Ориентир: число — рубли, строка — как написано («6000 THB», «149$»). */
  price?: number | string
  /** Где посмотреть. */
  url?: string
  /** Путь к фото 4:5 относительно корня сайта. */
  image: string
  /** `object-position`, например '65% 35%'. */
  imagePos?: string
  /** Подарок ещё не придуман: плита держит место, цена и ссылка не показываются. */
  pending?: boolean
  /** Выражается порядком в кольце и свечением передней плиты, не бейджем. */
  weight: 1 | 2 | 3
}
